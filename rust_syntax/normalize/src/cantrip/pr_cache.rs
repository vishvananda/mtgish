//! `pr_form`'s renders kept from one run of `planned::tracked_cached` to the next.
//!
//! A render is a pure function of its inputs and of the code that renders, and
//! it is about half of what a tracked run costs, while a change to the generator
//! changes a few modules. So each render is kept under a hash of everything it
//! reads: the module, the names and Oracle texts, the characteristics, and
//! `RENDER_SOURCES`, the bytes of the code it runs. A build whose `pr_form`
//! differs in any byte finds nothing kept.
//!
//! The module's two header lines say which generator wrote it, and change with
//! any change to the generator. They are comments, which a render reads past, so
//! they are left out of the hash, and a render whose text holds either is never
//! kept. A module that does not parse comes back as it went in, so what is kept
//! for it is that, not its text.
//!
//! The renders live in one file in the cache directory, `renders.bin`, written
//! whole (to a temporary file, then renamed) when the rows are, with what that
//! run rendered or found: it holds at most one render a card and nothing from an
//! older run. Workers only read it. Runs with `MTGISH_LOCAL_TOKENS` keep theirs
//! in `renders-local-tokens.bin`. With the cache, a corpus run takes about a
//! quarter of the instructions it takes without, or of a run after a change to
//! `pr_form`, which renders every card again.
use super::pr_form::{self, Characteristics};
use crate::corpus;
use std::collections::{HashMap, HashSet};
use std::io::Write;
use std::path::{Path, PathBuf};

/// Every file whose code a render runs: `pr_form` and what it calls in other
/// modules (`card_file::oracle_constant`, `costs::worded_apart`), the shared
/// tokens it reads, and the lock file that pins syn and prettyplease. A render
/// that comes to call code elsewhere must add that file here; the test
/// `pr_form_calls_only_what_the_cache_hashes` checks `pr_form` itself.
const RENDER_SOURCES: &[(&str, &[u8])] = &[
    ("cantrip/pr_cache.rs", include_bytes!("pr_cache.rs")),
    ("cantrip/pr_form.rs", include_bytes!("pr_form.rs")),
    ("cantrip/card_file.rs", include_bytes!("card_file.rs")),
    ("cantrip/costs.rs", include_bytes!("costs.rs")),
    ("cantrip/shared_tokens.tsv", include_bytes!("shared_tokens.tsv")),
    ("Cargo.lock", include_bytes!("../../../Cargo.lock")),
];

const MAGIC: &[u8] = b"mtgish pr_form renders 1\n";

/// Whether tokens are rendered as each card's own (`MTGISH_LOCAL_TOKENS`, for `tools/shared_tokens.py`).
/// Read once, as `pr_form` reads it.
fn local_tokens() -> bool {
    static LOCAL: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    *LOCAL.get_or_init(|| std::env::var_os("MTGISH_LOCAL_TOKENS").is_some())
}

/// The cache file: one for each way tokens are rendered, so the runs that
/// `shared_tokens.py` reads do not empty the cache of the others.
fn file_name() -> &'static str {
    match local_tokens() {
        true => "renders-local-tokens.bin",
        false => "renders.bin",
    }
}

/// The renders' own fingerprint: the code that renders, and the one setting it reads.
fn fingerprint() -> &'static str {
    static HASH: std::sync::OnceLock<String> = std::sync::OnceLock::new();
    HASH.get_or_init(|| {
        let mut bytes = Vec::new();
        for (name, source) in RENDER_SOURCES {
            field(&mut bytes, name.as_bytes());
            field(&mut bytes, source);
        }
        field(&mut bytes, if local_tokens() { b"local tokens" } else { b"shared tokens" });
        corpus::digest(&bytes)
    })
}

/// One input to a hash, its length first, so that no two lists of inputs run together alike.
fn field(out: &mut Vec<u8>, bytes: &[u8]) {
    out.extend_from_slice(&(bytes.len() as u64).to_le_bytes());
    out.extend_from_slice(bytes);
}

/// A header line of a generated module, which names the generator and its inputs.
fn signature(line: &str) -> bool {
    line.starts_with("// Generated by mtgish-ast, schema ") || line.starts_with("// Generator SHA256 ")
}

/// `raw` without its header lines, as an input to a hash.
fn unsigned_field(out: &mut Vec<u8>, raw: &str) {
    let lines: Vec<&str> = raw.split_inclusive('\n').filter(|line| !signature(line)).collect();
    out.extend_from_slice(&(lines.iter().map(|l| l.len()).sum::<usize>() as u64).to_le_bytes());
    for line in lines {
        out.extend_from_slice(line.as_bytes());
    }
}

/// What a render gave.
#[derive(Clone)]
enum Cached {
    Nothing,
    /// The module as it was passed in: it did not parse.
    AsGiven,
    Text(String),
}

impl Cached {
    fn of(rendered: &Option<String>, raw: &str) -> Option<Cached> {
        match rendered {
            None => Some(Cached::Nothing),
            Some(text) if text == raw => Some(Cached::AsGiven),
            // What reads past a header line must not show it, or it wasn't a comment.
            Some(text) if text.contains("Generated by mtgish-ast") || text.contains("Generator SHA256") => None,
            Some(text) => Some(Cached::Text(text.clone())),
        }
    }
    fn rendered(&self, raw: &str) -> Option<String> {
        match self {
            Cached::Nothing => None,
            Cached::AsGiven => Some(raw.to_string()),
            Cached::Text(text) => Some(text.clone()),
        }
    }
    fn tag(&self) -> u8 {
        match self {
            Cached::Nothing => 0,
            Cached::AsGiven => 1,
            Cached::Text(_) => 2,
        }
    }
}

/// A render to keep for the next run.
pub struct Kept {
    key: String,
    cached: Cached,
}

/// The renders an earlier run kept, or none where there is no cache.
pub struct Renders {
    dir: Option<PathBuf>,
    kept: HashMap<String, Cached>,
}

/// The cache directory a run uses: `MTGISH_PR_FORM_CACHE`, or `off` for none,
/// or by default `pr-form-cache` beside the binary, in its target directory.
pub fn default_dir() -> Option<PathBuf> {
    match std::env::var_os("MTGISH_PR_FORM_CACHE") {
        Some(dir) if dir.is_empty() || dir == "off" => None,
        Some(dir) => Some(PathBuf::from(dir)),
        None => Some(std::env::current_exe().ok()?.parent()?.join("pr-form-cache")),
    }
}

impl Renders {
    /// No cache: each render is done.
    pub fn none() -> Self {
        Self { dir: None, kept: HashMap::new() }
    }

    /// What `dir` holds from the last run of this `pr_form`: nothing if it holds
    /// no such file, another build's or one it cannot read whole.
    pub fn open(dir: &Path) -> Self {
        let kept = std::fs::read(dir.join(file_name())).ok().and_then(|bytes| read(&bytes)).unwrap_or_default();
        Self { dir: Some(dir.to_path_buf()), kept }
    }

    pub fn len(&self) -> usize {
        self.kept.len()
    }

    pub fn is_empty(&self) -> bool {
        self.kept.is_empty()
    }

    /// `pr_form::render`, from the cache where it has it.
    pub fn render(
        &self,
        raw: &str,
        name: &str,
        printed: &str,
        characteristics: Characteristics,
    ) -> (Option<String>, Option<Kept>) {
        if self.dir.is_none() {
            return (pr_form::render(raw, name, printed, characteristics), None);
        }
        let mut bytes = Vec::with_capacity(raw.len() + printed.len() + 256);
        field(&mut bytes, b"render");
        field(&mut bytes, fingerprint().as_bytes());
        unsigned_field(&mut bytes, raw);
        field(&mut bytes, name.as_bytes());
        field(&mut bytes, printed.as_bytes());
        let characteristics_tag: &[u8] = match characteristics {
            Characteristics::Inline => b"inline",
            Characteristics::Oracle => b"oracle",
        };
        field(&mut bytes, characteristics_tag);
        self.through(corpus::digest(&bytes), raw, || pr_form::render(raw, name, printed, characteristics))
    }

    /// `pr_form::render_faces`, from the cache where it has it.
    pub fn render_faces(
        &self,
        raw: &str,
        modules: &[&str],
        faces: &[(&str, &str)],
    ) -> (Option<String>, Option<Kept>) {
        if self.dir.is_none() {
            return (pr_form::render_faces(raw, modules, faces), None);
        }
        let mut bytes = Vec::with_capacity(raw.len() + 1024);
        field(&mut bytes, b"render_faces");
        field(&mut bytes, fingerprint().as_bytes());
        unsigned_field(&mut bytes, raw);
        field(&mut bytes, &(modules.len() as u64).to_le_bytes());
        for module in modules {
            field(&mut bytes, module.as_bytes());
        }
        field(&mut bytes, &(faces.len() as u64).to_le_bytes());
        for (name, printed) in faces {
            field(&mut bytes, name.as_bytes());
            field(&mut bytes, printed.as_bytes());
        }
        self.through(corpus::digest(&bytes), raw, || pr_form::render_faces(raw, modules, faces))
    }

    fn through(&self, key: String, raw: &str, render: impl FnOnce() -> Option<String>) -> (Option<String>, Option<Kept>) {
        if let Some(cached) = self.kept.get(&key) {
            return (cached.rendered(raw), Some(Kept { key, cached: cached.clone() }));
        }
        let rendered = render();
        let kept = Cached::of(&rendered, raw).map(|cached| Kept { key, cached });
        (rendered, kept)
    }

    /// Where this run's renders go, if it keeps any.
    pub fn keeper(&self) -> Keeper {
        let file = self.dir.as_ref().and_then(|dir| {
            let made = std::fs::create_dir_all(dir).map_err(Into::into).and_then(|_| {
                let mut file = corpus::Artifact::create(&dir.join(file_name()))?;
                file.write_all(MAGIC)?;
                file.write_all(fingerprint().as_bytes())?;
                file.write_all(b"\n")?;
                corpus::Result::Ok(file)
            });
            made.map_err(|e| eprintln!("pr_form cache {}: {e}; renders are not kept", dir.display())).ok()
        });
        Keeper { file, written: HashSet::new(), found: 0, rendered: 0 }
    }

    /// Whether `kept` came from the cache.
    pub fn had(&self, kept: &Kept) -> bool {
        self.kept.contains_key(&kept.key)
    }
}

/// The renders of a run, written in the order the run visits them.
pub struct Keeper {
    file: Option<corpus::Artifact>,
    written: HashSet<String>,
    pub found: usize,
    pub rendered: usize,
}

impl Keeper {
    pub fn keep(&mut self, kept: Kept, found: bool) -> corpus::Result<()> {
        match found {
            true => self.found += 1,
            false => self.rendered += 1,
        }
        let Some(file) = &mut self.file else { return Ok(()) };
        if !self.written.insert(kept.key.clone()) {
            return Ok(());
        }
        let text = match &kept.cached {
            Cached::Text(text) => text.as_bytes(),
            _ => &[],
        };
        file.write_all(kept.key.as_bytes())?;
        file.write_all(&[kept.cached.tag()])?;
        file.write_all(&(text.len() as u32).to_le_bytes())?;
        file.write_all(text)?;
        Ok(())
    }

    /// Replace the last run's renders with this one's.
    pub fn commit(self) -> corpus::Result<()> {
        match self.file {
            Some(file) => file.commit(),
            None => Ok(()),
        }
    }
}

/// The renders in a cache file, if it is this build's and whole.
fn read(bytes: &[u8]) -> Option<HashMap<String, Cached>> {
    let rest = bytes.strip_prefix(MAGIC)?;
    let rest = rest.strip_prefix(fingerprint().as_bytes())?;
    let mut rest = rest.strip_prefix(b"\n")?;
    let mut kept = HashMap::new();
    while !rest.is_empty() {
        let (key, tail) = rest.split_at_checked(64)?;
        let (&tag, tail) = tail.split_first()?;
        let (length, tail) = tail.split_at_checked(4)?;
        let length = u32::from_le_bytes(length.try_into().ok()?) as usize;
        let (text, tail) = tail.split_at_checked(length)?;
        let cached = match tag {
            0 if text.is_empty() => Cached::Nothing,
            1 if text.is_empty() => Cached::AsGiven,
            2 => Cached::Text(String::from_utf8(text.to_vec()).ok()?),
            _ => return None,
        };
        kept.insert(String::from_utf8(key.to_vec()).ok()?, cached);
        rest = tail;
    }
    Some(kept)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The cache hashes the files `RENDER_SOURCES` lists as the code of a render:
    /// `pr_form` must call nothing elsewhere in the crate that is not one of them.
    #[test]
    fn pr_form_calls_only_what_the_cache_hashes() {
        let source = include_str!("pr_form.rs");
        assert!(!source.contains("crate::"), "pr_form reads the crate beyond its cache's sources");
        for (at, _) in source.match_indices("super::") {
            let module: String =
                source[at + "super::".len()..].chars().take_while(|c| c.is_alphanumeric() || *c == '_').collect();
            let listed = RENDER_SOURCES.iter().any(|(name, _)| *name == format!("cantrip/{module}.rs"));
            assert!(listed, "pr_form calls super::{module}, which RENDER_SOURCES does not hash");
        }
    }

    const MODULE: &str = "// Generated by mtgish-ast, schema 1, normalized SHA256 00.\n// Generator SHA256 aa; Cantrip API SHA256 bb.\n#[allow(unused_imports)] use cantrip_api::*;\npub static CARD: CardDef = CardDef { name: \"Bear\", ..CardDef::BLANK };\n";

    fn dir(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("mtgish-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        dir
    }

    /// A kept render is the one a render gives, for the same module from another
    /// generator too, and a module that changes is rendered again.
    #[test]
    fn a_kept_render_is_the_render() {
        let dir = dir("pr_cache_kept");
        let first = Renders::open(&dir);
        let (rendered, kept) = first.render(MODULE, "Bear", "", Characteristics::Inline);
        assert_eq!(rendered, pr_form::render(MODULE, "Bear", "", Characteristics::Inline));
        let mut keeper = first.keeper();
        keeper.keep(kept.unwrap(), false).unwrap();
        keeper.commit().unwrap();
        let second = Renders::open(&dir);
        assert_eq!(second.len(), 1);
        let regenerated = MODULE.replace("SHA256 aa", "SHA256 cc");
        let (again, kept) = second.render(&regenerated, "Bear", "", Characteristics::Inline);
        assert!(second.had(kept.as_ref().unwrap()));
        assert_eq!(again, rendered);
        let changed = MODULE.replace("Bear", "Bears");
        let (_, kept) = second.render(&changed, "Bear", "", Characteristics::Inline);
        assert!(!second.had(kept.as_ref().unwrap()));
        let (_, kept) = second.render(MODULE, "Bear", "Flash", Characteristics::Inline);
        assert!(!second.had(kept.as_ref().unwrap()));
    }

    /// A module that doesn't parse comes back as passed, header lines and all.
    #[test]
    fn a_module_that_does_not_parse_comes_back_as_passed() {
        let dir = dir("pr_cache_unparsed");
        let broken = format!("{MODULE}fn (");
        let first = Renders::open(&dir);
        let (rendered, kept) = first.render(&broken, "Bear", "", Characteristics::Oracle);
        assert_eq!(rendered.as_deref(), Some(broken.as_str()));
        let mut keeper = first.keeper();
        keeper.keep(kept.unwrap(), false).unwrap();
        keeper.commit().unwrap();
        let regenerated = broken.replace("SHA256 aa", "SHA256 cc");
        let (again, _) = Renders::open(&dir).render(&regenerated, "Bear", "", Characteristics::Oracle);
        assert_eq!(again, Some(regenerated));
    }

    /// Another build's file, or one cut short, is read as empty.
    #[test]
    fn another_builds_file_is_empty() {
        let dir = dir("pr_cache_other");
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join(file_name()), [MAGIC, &[b'0'; 64], b"\n"].concat()).unwrap();
        assert!(Renders::open(&dir).is_empty());
        let mut whole = [MAGIC, fingerprint().as_bytes(), b"\n"].concat();
        whole.extend_from_slice(&[b'a'; 64]);
        whole.push(2);
        whole.extend_from_slice(&5u32.to_le_bytes());
        whole.extend_from_slice(b"text");
        std::fs::write(dir.join(file_name()), &whole).unwrap();
        assert!(Renders::open(&dir).is_empty());
    }
}
