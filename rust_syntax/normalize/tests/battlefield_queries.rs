#[test]
fn battlefield_access_is_exact_about_scope_kind_and_wrappers() {
    let battlefield = ObjectSet::battlefield(ObjectFilter::Any);
    assert!(battlefield.battlefield_filter().is_some());
    let canonical = ObjectSet::Zone {
        scope: ZoneScope::Shared(EventZone::Battlefield),
        kind: ObjectKind::Permanent,
        filter: ObjectFilter::Any,
    };
    assert!(canonical.battlefield_filter().is_some());
    for query in [
        ObjectSet::Zone {
            scope: ZoneScope::Shared(EventZone::Battlefield),
            kind: ObjectKind::Card,
            filter: ObjectFilter::Any,
        },
        ObjectSet::Zone {
            scope: ZoneScope::Shared(EventZone::Battlefield),
            kind: ObjectKind::Any,
            filter: ObjectFilter::Any,
        },
        ObjectSet::Zone {
            scope: ZoneScope::Players {
                zone: EventZone::Battlefield,
                players: PlayerSet::All,
            },
            kind: ObjectKind::Permanent,
            filter: ObjectFilter::Any,
        },
        ObjectSet::Zone {
            scope: ZoneScope::Shared(EventZone::Exile),
            kind: ObjectKind::Card,
            filter: ObjectFilter::Any,
        },
        ObjectSet::Selected(ResultId(3)),
        ObjectSet::Observed(ResultId(3)),
        ObjectSet::Created(ResultId(3)),
        ObjectSet::InZone {
            objects: Box::new(ObjectSet::One(ObjectRef::Source)),
            zone: EventZone::Battlefield,
        },
    ] {
        assert!(query.battlefield_filter().is_none(), "{query:?}");
    }
}

#[test]
fn printed_query_families_validate_and_roundtrip() {
    for line in include_str!("fixtures/battlefield_queries.ronl").lines() {
        let source: OracleCard = ron::from_str(line).unwrap();
        let lowered = unified::lower(&source);
        assert!(lowered.diagnostics.is_empty(), "{:?}", lowered.diagnostics);
        validate::unified(&lowered.card).unwrap();
        unified::round_trip(&lowered.card).unwrap();
        let mut value = serde_json::to_value(&lowered.card).unwrap();
        query_aliases::battlefield(&mut value);
        let canonical: UnifiedCard = serde_json::from_value(value).unwrap();
        validate::unified(&canonical).unwrap();
        unified::round_trip(&canonical).unwrap();
    }
}

#[cfg(feature = "cantrip")]
#[test]
fn both_spellings_generate_the_same_modules_or_exact_gaps() {
    fn body(code: &str) -> String {
        code.lines()
            .filter(|line| {
                !line.starts_with("// Generated by mtgish-ast, schema ")
                    && !line.starts_with("// Generator SHA256 ")
            })
            .collect::<Vec<_>>()
            .join("\n")
    }
    for line in include_str!("fixtures/battlefield_queries.ronl").lines() {
        let source: OracleCard = ron::from_str(line).unwrap();
        let original = unified::lower(&source).card;
        let mut value = serde_json::to_value(&original).unwrap();
        query_aliases::battlefield(&mut value);
        let canonical: UnifiedCard = serde_json::from_value(value).unwrap();
        let old = mtgish_ast::cantrip::whole_module(&source, &original);
        let new = mtgish_ast::cantrip::whole_module(&source, &canonical);
        match (old, new) {
            (Ok(old), Ok(new)) => assert_eq!(body(&old), body(&new), "{line}"),
            (Err(_), Err(_)) => assert_eq!(
                serde_json::to_value(mtgish_ast::cantrip::whole_gaps(&source, &original)).unwrap(),
                serde_json::to_value(mtgish_ast::cantrip::whole_gaps(&source, &canonical)).unwrap(),
                "{line}"
            ),
            other => panic!("{line}: {other:?}"),
        }
    }
}

#[cfg(feature = "cantrip")]
#[test]
fn permanent_statics_do_not_become_everywhere_card_statics() {
    for line in include_str!("fixtures/battlefield_queries.ronl").lines() {
        let source: OracleCard = ron::from_str(line).unwrap();
        let original = unified::lower(&source).card;
        if !["Crusade", "Humility", "Ashes of the Fallen"]
            .contains(&original.faces[0].name.as_str())
        {
            continue;
        }
        let mut value = serde_json::to_value(&original).unwrap();
        query_aliases::battlefield(&mut value);
        let canonical: UnifiedCard = serde_json::from_value(value).unwrap();
        let code = mtgish_ast::cantrip::whole_module(&source, &canonical).unwrap();
        assert_eq!(
            code.contains(".everywhere()"),
            original.faces[0].name == "Ashes of the Fallen",
            "{code}"
        );
    }
}

#[test]
fn player_scoped_battlefields_remain_invalid_and_card_queries_stay_distinct() {
    let source:OracleCard=ron::from_str(r#"Card(Name: "Scope validation", Typeline: (Supertypes: [], Cardtypes: [Sorcery], Subtypes: []), Rules: [SpellActions(ActionList([DrawACard]))])"#).unwrap();
    let mut card = mtgish_ast::lower::card(&source).unwrap();
    for (scope, kind, valid) in [
        (
            ZoneScope::Shared(EventZone::Battlefield),
            ObjectKind::Permanent,
            true,
        ),
        (
            ZoneScope::Shared(EventZone::Battlefield),
            ObjectKind::Card,
            true,
        ),
        (
            ZoneScope::Players {
                zone: EventZone::Battlefield,
                players: PlayerSet::All,
            },
            ObjectKind::Permanent,
            false,
        ),
    ] {
        let Ability::Spell { body, .. } = &mut card.abilities[0] else {
            panic!()
        };
        body.instructions[0] = Instruction::Effect {
            result: ResultId(0),
            operation: Operation::Tap {
                objects: ObjectSet::Zone {
                    scope,
                    kind,
                    filter: ObjectFilter::Any,
                },
                tapped: true,
            },
        };
        assert_eq!(validate::card(&card).is_ok(), valid);
    }
}

#[test]
fn complete_producer_records_change_only_query_aliases_and_schema_stamps() {
    let source: Vec<_> = include_str!("fixtures/battlefield_queries.ronl")
        .lines()
        .collect();
    let before: Vec<_> = include_str!("fixtures/battlefield_queries_before.jsonl")
        .lines()
        .collect();
    assert_eq!((source.len(), before.len()), (30, 30));
    for (line, before) in source.into_iter().zip(before) {
        let source: OracleCard = ron::from_str(line).unwrap();
        let mut expected: Value = serde_json::from_str(before).unwrap();
        query_aliases::battlefield(&mut expected);
        query_aliases::value_choices(&mut expected);
        expected["schema_version"] = json!(SCHEMA_VERSION);
        for face in expected["faces"].as_array_mut().unwrap() {
            face["schema_version"] = json!(SCHEMA_VERSION);
        }
        query_aliases::movement_defaults(&mut expected);
        assert_eq!(
            serde_json::to_value(unified::lower(&source).card).unwrap(),
            expected,
            "{line}"
        );
    }
}
